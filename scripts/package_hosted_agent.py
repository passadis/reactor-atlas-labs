"""Stage the hosted agent's code-deploy folder: agents/src/atlas-incident-agent/.

    uv run python -m scripts.package_hosted_agent

`azd deploy -C agents` zips this folder and Foundry installs `requirements.txt` in the cloud
(`remote_build`). The folder is a build artefact, regenerated on every deploy and gitignored:

    main.py              entry point: atlas_hosted_agent.agent.main()
    requirements.txt     exact pins exported from uv.lock (third-party only)
    atlas_common/        } copied from src/ as plain source packages, importable from the
    atlas_agent/         } zip root. Not duplicated agent code: the one definition, shipped.
    atlas_hosted_agent/  }

Why copy rather than list the workspace packages as requirements: they are local uv workspace
members, not published anywhere, so a cloud `pip install` cannot resolve them. Shipping them as
source keeps one definition (atlas_agent.factory) running in all three surfaces.
"""

from __future__ import annotations

import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "agents" / "src" / "atlas-incident-agent"
PACKAGES = {
    "atlas_common": ROOT / "src" / "atlas_common" / "atlas_common",
    "atlas_agent": ROOT / "src" / "atlas_agent" / "atlas_agent",
    "atlas_hosted_agent": ROOT / "src" / "atlas_hosted_agent" / "atlas_hosted_agent",
}
MAIN = '''"""Foundry hosted agent entry point. Generated by scripts/package_hosted_agent.py."""

from atlas_hosted_agent.agent import main

if __name__ == "__main__":
    main()
'''
IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".pytest_cache")


def export_requirements() -> str:
    uv = shutil.which("uv") or "uv"
    out = subprocess.run(
        [uv, "export", "--frozen", "--no-dev", "--no-hashes", "--no-header",
         "--package", "atlas-hosted-agent", "--no-emit-workspace"],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout
    pins = [line for line in out.splitlines() if line.strip() and not line.lstrip().startswith("#")]
    loose = [p for p in pins if "==" not in p]
    if loose:
        raise SystemExit(f"refusing to ship unpinned requirements: {loose[:5]}")
    return "\n".join(pins) + "\n"


def digest(folder: Path) -> str:
    h = hashlib.sha256()
    for path in sorted(p for p in folder.rglob("*") if p.is_file()):
        h.update(path.relative_to(folder).as_posix().encode())
        h.update(path.read_bytes())
    return h.hexdigest()[:16]


def write_rai_policy_ref() -> str:
    """agents/.generated/rai-policy.yaml, `$ref`'d from agents/azure.yaml `policies:`.

    azure.ai.agents 1.0.0-beta.15 does not substitute ${VAR} inside `policies`, so a placeholder
    reached Foundry verbatim and the guardrail failed open (docs/API-NOTES.md 12). The resolved
    ARM id is written here from the agents azd env instead; azure.yaml stays env-agnostic.
    """
    env_file = ROOT / "agents" / ".azure" / os.environ.get("AZURE_ENV_NAME", "atlas") / ".env"
    values = dict(
        line.split("=", 1) for line in env_file.read_text(encoding="utf-8").splitlines()
        if "=" in line
    )
    policy_id = values.get("ATLAS_RAI_POLICY_ID", "").strip().strip('"')
    if not policy_id.startswith("/subscriptions/") or "/raiPolicies/" not in policy_id:
        raise SystemExit(f"ATLAS_RAI_POLICY_ID missing or malformed in {env_file}; "
                         "run scripts/seed_agents_env.sh")
    out = ROOT / "agents" / ".generated" / "rai-policy.yaml"
    out.parent.mkdir(exist_ok=True)
    out.write_text(f"type: rai_policy\nraiPolicyName: {policy_id}\n", encoding="utf-8")
    return policy_id.rsplit("/", 1)[-1]


def main() -> int:
    policy = write_rai_policy_ref()
    print(f"guardrail: {policy} (agents/.generated/rai-policy.yaml)")
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    for name, source in PACKAGES.items():
        shutil.copytree(source, OUT / name, ignore=IGNORE)
    (OUT / "main.py").write_text(MAIN, encoding="utf-8")
    requirements = export_requirements()
    (OUT / "requirements.txt").write_text(requirements, encoding="utf-8")
    print(f"staged {OUT.relative_to(ROOT)}: {len(requirements.splitlines())} pinned requirements, "
          f"content digest {digest(OUT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
